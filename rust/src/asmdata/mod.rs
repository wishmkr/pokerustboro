//! The assembled data (scripts, maps, songs, multiboot images) as Rust
//! statics, generated from the objects by tools/rustport/obj2rs.py.
#![allow(non_upper_case_globals, non_snake_case, clippy::all)]

/// A section with its bytes as they were (alignment 1).
#[repr(transparent)]
pub struct Sec<T>(pub T);
/// A word-aligned section.
#[repr(C, align(4))]
pub struct A4<T>(pub T);
/// An address in a section.
#[repr(transparent)]
#[derive(Clone, Copy)]
pub struct Ptr(pub *const u8);
// SAFETY: the data is never written but by the sound code, on one core.
unsafe impl<T> Sync for Sec<T> {}
unsafe impl<T> Sync for A4<T> {}
unsafe impl Sync for Ptr {}

